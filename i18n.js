  let lang = "en";

  function normalize(code) {
    if (!code) return null;
    const c = String(code).replace("_", "-");
    if (dict[c]) return c;
    const base = c.split("-")[0].toLowerCase();
    const map = {
      en: "en",
      zh: c.toLowerCase().includes("tw") || c.toLowerCase().includes("hk") || c.toLowerCase().includes("hant")
        ? "zh-TW"
        : "zh-CN",
      ja: "ja",
      ko: "ko",
      es: "es",
      fr: "fr",
      de: "de",
      pt: "pt",
      ru: "ru",
    };
    return map[base] || null;
  }


  function pathLocale() {
    const seg = (location.pathname || "/").split("/").filter(Boolean)[0];
    if (!seg) return null;
    if (dict[seg]) return seg;
    return normalize(seg);
  }

  function pathForLang(code) {
    return "/" + code + "/";
  }

  function detect() {
    const fromPath = pathLocale();
    if (fromPath) return fromPath;
    // Root "/" is the English canonical entry for SEO
    if (!location.pathname || location.pathname === "/") return "en";
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && dict[saved]) return saved;
    } catch (_) {}
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
    return normalize(nav) || "en";
  }

  function t(key, vars) {
    const table = dict[lang] || dict.en;
    let s = table[key] ?? dict.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(v));
      }
    }
    return s;
  }

  function setLang(next, opts) {
    const options = opts || {};
    const navigate = options.navigate !== false;
    if (!dict[next]) next = "en";

    const currentPathLang = pathLocale() || ((location.pathname === "/" || location.pathname === "") ? "en" : null);

    // Language switcher: move to the matching locale URL
    if (navigate && currentPathLang && currentPathLang !== next) {
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch (_) {}
      location.assign(pathForLang(next));
      return;
    }

    lang = next;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_) {}
    document.documentElement.lang = lang;
    document.title = t("meta.title");
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t("meta.description"));
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", t("meta.title"));
    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute("content", t("meta.description"));
    const twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute("content", t("meta.title"));
    const twDesc = document.querySelector('meta[name="twitter:description"]');
    if (twDesc) twDesc.setAttribute("content", t("meta.description"));
    applyDom();
    const sel = document.getElementById("lang-select");
    if (sel && sel.value !== lang) sel.value = lang;
    document.dispatchEvent(new CustomEvent("hogwords:lang", { detail: { lang } }));
  }

  function applyDom() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (key) el.innerHTML = t(key);
    });
  }

  function buildSwitcher(container) {
    if (!container) return;
    container.innerHTML = "";
    const label = document.createElement("label");
    label.className = "lang-switch";
    label.setAttribute("data-i18n-aria", "lang.aria");
    label.setAttribute("aria-label", t("lang.aria"));
    const span = document.createElement("span");
    span.className = "lang-icon";
    span.setAttribute("aria-hidden", "true");
    span.textContent = "🌐";
    const select = document.createElement("select");
    select.id = "lang-select";
    select.setAttribute("aria-label", t("lang.aria"));
    LOCALES.forEach((L) => {
      const opt = document.createElement("option");
      opt.value = L.code;
      opt.textContent = L.label;
      if (L.code === lang) opt.selected = true;
      select.appendChild(opt);
    });
    select.addEventListener("change", () => setLang(select.value, { navigate: true }));
    label.appendChild(span);
    label.appendChild(select);
    container.appendChild(label);
  }

  function init() {
    lang = detect();
    document.documentElement.lang = lang;
    buildSwitcher(document.getElementById("lang-switcher"));
    setLang(lang, { navigate: false });
  }

  return {
    LOCALES,
    t,
    setLang,
    getLang: () => lang,
    init,
    applyDom,
  };
